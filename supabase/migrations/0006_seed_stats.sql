-- المحتوى إلى القاعدة" الموثّق سلفاً في CLAUDE.md (أسماء الأعمدة مطابقة
-- عمداً لحقول content.js لهذا الغرض بالضبط).
-- ----------------------------------------------------------------------------
-- القيم هنا هي نفسها الموجودة حالياً بـ content.js (بيانات تجريبية ⚠️) —
-- الهدف تمكين تعديلها من شاشة "الإحصائيات" الجديدة بلوحة الإدارة، لا
-- تغييرها الآن. لا قيد فريد على label فالجدول لم يُصمَّم بواحد؛ الإدراج
-- محروس بـ NOT EXISTS بدل ON CONFLICT حتى يبقى آمناً لإعادة التشغيل.
-- ============================================================================

insert into public.stats (label, value, suffix, icon, sort_order)
select v.label, v.value, v.suffix, v.icon, v.sort_order
from (values
  ('طالب وطالبة',    1250, '+', '🎓', 1),
  ('مدرّب معتمد',      38,   '',  '👩‍🏫', 2),
  ('شريك ومؤسسة',      24,   '',  '🤝', 3),
  ('جائزة وميدالية',   47,   '',  '🏆', 4),
  ('برنامج تدريبي',    32,   '',  '📚', 5),
  ('مشروع روبوت',      180,  '+', '🤖', 6)
) as v(label, value, suffix, icon, sort_order)
where not exists (select 1 from public.stats s where s.label = v.label);
