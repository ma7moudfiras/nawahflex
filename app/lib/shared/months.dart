/// أسماء الأشهر العربية (الشامية) — نقطة تحرير واحدة لكل مكان يعرض شهراً
/// (المستحقات، مستحقات المدرّبين، أشهر اشتراك الطالب).
const arabicMonthNames = [
  'كانون الثاني',
  'شباط',
  'آذار',
  'نيسان',
  'أيار',
  'حزيران',
  'تموز',
  'آب',
  'أيلول',
  'تشرين الأول',
  'تشرين الثاني',
  'كانون الأول',
];

String arabicMonthLabel(DateTime month) =>
    '${arabicMonthNames[month.month - 1]} ${month.year}';
